import { useEffect, useMemo, useRef, useState } from 'react'
import { useNavigate } from 'react-router-dom'
import { MoreHorizontal, Pencil, Plus, Search, Trash2 } from 'lucide-react'
import {
  useCreateWorkflow,
  useDeleteWorkflow,
  useSaveWorkflow,
  useWorkflows,
  type WorkflowSummary,
} from '../api/workflows'
// (legacy duplicate import removed below)
import { useServices, type ServiceRow } from '../api/services'
import { confirmDialog } from '../stores/confirm'
import { useToastStore } from '../stores/toast'

type Tab = 'all' | 'mine' | 'template' | 'published'

const TABS: { id: Tab; label: string }[] = [
  { id: 'all', label: '全部' },
  { id: 'mine', label: '我的' },
  { id: 'template', label: '模板' },
  { id: 'published', label: '已发布' },
]

export default function WorkflowsList() {
  // Hide auto-generated trivial workflows by default; the m08 page is for
  // hand-built DAGs.
  const { data: workflows, isLoading, error } = useWorkflows({ autoGenerated: false })
  const { data: services } = useServices()
  const navigate = useNavigate()
  const [tab, setTab] = useState<Tab>('all')
  const [search, setSearch] = useState('')

  const create = useCreateWorkflowAndGo()
  const del = useDeleteWorkflow()
  const save = useSaveWorkflow()
  const toast = useToastStore((s) => s.add)

  const handleDelete = async (wf: WorkflowSummary) => {
    if (!(await confirmDialog({ message: `确认删除工作流 "${wf.name}"?\n这是不可撤销的操作。`, danger: true, confirmText: '删除' }))) return
    del.mutate(String(wf.id), {
      onSuccess: () => toast(`已删除 ${wf.name}`, 'success'),
      onError: (e) => toast(`删除失败：${(e as Error).message}`, 'error'),
    })
  }

  const handleRename = (wf: WorkflowSummary) => {
    const name = window.prompt('重命名工作流', wf.name)?.trim()
    if (!name || name === wf.name) return
    save.mutate({ id: String(wf.id), name }, {
      onSuccess: () => toast(`已重命名为「${name}」`, 'success'),
      onError: (e) => toast(`重命名失败：${(e as Error).message}`, 'error'),
    })
  }

  const handlePublish = (wf: WorkflowSummary) => {
    // 跳到画布编辑器并自动弹发布对话框（query 由 Topbar 检测）。
    // 直接在列表里弹会拿不到完整 nodes 数据 + react-flow context。
    navigate(`/workflows/${wf.id}?publish=1`)
  }

  // Group services by source workflow id so each card can show its
  // associated service link without an extra round-trip per row.
  const servicesByWorkflow = useMemo(() => indexServicesByWorkflow(services ?? []), [services])
  const counts = useMemo(() => buildCounts(workflows ?? []), [workflows])
  const filtered = useMemo(
    () => filter(workflows ?? [], tab, search),
    [workflows, tab, search],
  )

  return (
    <div
      style={{
        position: 'absolute',
        inset: 0,
        overflow: 'auto',
        background: 'var(--bg)',
      }}
    >
      <div className="console-page console-controls">
        <div className="console-page-header">
          <div style={{ flex: 1 }}>
            <h1 className="console-title">Workflow</h1>
            <p className="console-description">
              搭建节点化工作流 · 发布为「服务」后对外暴露 API 端点，通过 API Key 调用
            </p>
          </div>
          <div style={{ display: 'flex', gap: 8, alignItems: 'center' }}>
            <div style={{ position: 'relative' }}>
              <Search
                size={14}
                style={{
                  position: 'absolute',
                  left: 8,
                  top: '50%',
                  transform: 'translateY(-50%)',
                  color: 'var(--muted)',
                }}
              />
              <input
                value={search}
                onChange={(e) => setSearch(e.target.value)}
                placeholder="搜索 workflow..."
                style={{
                  width: 220,
                  background: 'var(--bg-accent)',
                  color: 'var(--text)',
                  border: '1px solid var(--border)',
                  borderRadius: 4,
                  padding: '7px 9px 7px 28px',
                  fontSize: 12,
                }}
              />
            </div>
            <button
              type="button"
              onClick={() => create.mutate()}
              disabled={create.isPending}
              style={{
                display: 'flex',
                alignItems: 'center',
                gap: 4,
                padding: '7px 12px',
                background: 'var(--accent)',
                color: '#fff',
                border: 'none',
                borderRadius: 4,
                fontSize: 12,
                cursor: create.isPending ? 'wait' : 'pointer',
                opacity: create.isPending ? 0.6 : 1,
              }}
            >
              <Plus size={14} />
              新建
            </button>
          </div>
        </div>

        <div style={{ display: 'flex', gap: 4, marginBottom: 14 }}>
          {TABS.map((t) => {
            const n = counts[t.id]
            const active = tab === t.id
            return (
              <button
                key={t.id}
                type="button"
                onClick={() => setTab(t.id)}
                style={{
                  padding: '6px 12px',
                  background: active
                    ? 'var(--accent-subtle, rgba(99,102,241,0.1))'
                    : 'transparent',
                  color: active ? 'var(--accent)' : 'var(--muted)',
                  border: '1px solid',
                  borderColor: active ? 'var(--accent)' : 'var(--border)',
                  borderRadius: 4,
                  fontSize: 12,
                  cursor: 'pointer',
                }}
              >
                {t.label} {n}
              </button>
            )
          })}
        </div>

        {isLoading && <Loading />}
        {error && <ErrorBlock message={(error as Error).message} />}
        {workflows && workflows.length === 0 && (
          <Empty onCreate={() => create.mutate()} />
        )}

        {filtered && filtered.length > 0 && (
          <div
            style={{
              display: 'grid',
              gridTemplateColumns: 'repeat(auto-fill, minmax(260px, 1fr))',
              gap: 12,
            }}
          >
            {filtered.map((wf) => (
              <WorkflowCard
                key={wf.id}
                wf={wf}
                service={servicesByWorkflow.get(String(wf.id)) ?? null}
                onOpen={() => navigate(`/workflows/${wf.id}`)}
                onDetail={(svcId) => navigate(`/services/${svcId}`)}
                onPublish={() => handlePublish(wf)}
                onDelete={() => handleDelete(wf)}
                onRename={() => handleRename(wf)}
              />
            ))}
            <NewWorkflowCard onClick={() => create.mutate()} />
          </div>
        )}
      </div>
    </div>
  )
}

// ---------- card ----------

function WorkflowCard({
  wf,
  service,
  onOpen,
  onDetail,
  onPublish,
  onDelete,
  onRename,
}: {
  wf: WorkflowSummary
  service: ServiceRow | null
  onOpen: () => void
  onDetail: (serviceId: string) => void
  onPublish: () => void
  onDelete: () => void
  onRename: () => void
}) {
  const nodeCount = wf.nodes?.length ?? 0
  // workflow status (draft / published) 与是否产出 service 是**两个独立状态**。
  // 之前混在一起判断，导致已 published 的 workflow 卡片底部仍出现"未发布
  // 为服务"+红色按钮，跟头部"已发布"绿徽章语义冲突。现在拆开：
  //   - badge 只看 wf.status
  //   - 底部专门看 service 关联
  const isPublished = wf.status === 'published'
  const isTemplate = wf.is_template
  // menuPos=null → 关；{x,y} → 在该屏幕坐标弹菜单(··· 按钮 / 右键卡片都走它)。
  const [menuPos, setMenuPos] = useState<{ x: number; y: number } | null>(null)
  const menuRef = useRef<HTMLDivElement>(null)
  useEffect(() => {
    if (!menuPos) return
    const onDoc = (e: MouseEvent) => {
      if (menuRef.current && !menuRef.current.contains(e.target as Node)) {
        setMenuPos(null)
      }
    }
    document.addEventListener('mousedown', onDoc)
    return () => document.removeEventListener('mousedown', onDoc)
  }, [menuPos])
  return (
    <div
      onContextMenu={(e) => {
        e.preventDefault()
        setMenuPos({ x: e.clientX, y: e.clientY })
      }}
      style={{
        background: 'var(--bg-accent)',
        border: '1px solid var(--border)',
        borderRadius: 8,
        padding: 14,
        display: 'flex',
        flexDirection: 'column',
        gap: 10,
        position: 'relative',
      }}
    >
      {/* 右上角 ··· 按钮：在按钮下方弹同一菜单(右键卡片也弹,定位到光标)。 */}
      <div style={{ position: 'absolute', top: 8, right: 8, zIndex: 2 }}>
        <button
          type="button"
          onClick={(e) => {
            e.stopPropagation()
            const r = e.currentTarget.getBoundingClientRect()
            setMenuPos(menuPos ? null : { x: r.right - 150, y: r.bottom + 4 })
          }}
          title="更多操作"
          style={{
            width: 24,
            height: 24,
            borderRadius: 4,
            border: 'none',
            background: menuPos ? 'var(--bg)' : 'transparent',
            color: 'var(--muted)',
            cursor: 'pointer',
            display: 'flex',
            alignItems: 'center',
            justifyContent: 'center',
          }}
        >
          <MoreHorizontal size={14} />
        </button>
      </div>

      {/* 卡片菜单(··· 或右键触发):重命名 / 删除。屏幕坐标定位(position:fixed)。 */}
      {menuPos && (
        <div
          ref={menuRef}
          style={{
            position: 'fixed',
            left: menuPos.x,
            top: menuPos.y,
            zIndex: 50,
            minWidth: 150,
            background: 'var(--bg-elevated, var(--bg))',
            border: '1px solid var(--border)',
            borderRadius: 6,
            boxShadow: '0 8px 24px rgba(0,0,0,0.4)',
            padding: '4px 0',
          }}
        >
          {[
            { icon: <Pencil size={12} />, label: '重命名', danger: false, run: onRename },
            { icon: <Trash2 size={12} />, label: '删除', danger: true, run: onDelete },
          ].map((it) => (
            <button
              key={it.label}
              type="button"
              onClick={(e) => {
                e.stopPropagation()
                setMenuPos(null)
                it.run()
              }}
              style={{
                display: 'flex',
                alignItems: 'center',
                gap: 8,
                width: '100%',
                padding: '6px 12px',
                background: 'transparent',
                border: 'none',
                color: it.danger ? 'var(--accent, #ef4444)' : 'var(--text)',
                fontSize: 12,
                cursor: 'pointer',
                textAlign: 'left',
              }}
              onMouseEnter={(e) => {
                e.currentTarget.style.background = 'var(--bg-hover, rgba(255,255,255,0.05))'
              }}
              onMouseLeave={(e) => {
                e.currentTarget.style.background = 'transparent'
              }}
            >
              {it.icon}
              {it.label}
            </button>
          ))}
        </div>
      )}

      <button
        type="button"
        onClick={onOpen}
        style={{
          textAlign: 'left',
          background: 'transparent',
          border: 'none',
          padding: 0,
          cursor: 'pointer',
          color: 'var(--text)',
        }}
      >
        <ThumbStrip count={nodeCount} />
        <div
          style={{
            display: 'flex',
            alignItems: 'baseline',
            gap: 6,
            marginBottom: 4,
          }}
        >
          <span style={{ fontSize: 13, color: 'var(--text)', fontWeight: 500 }}>
            {wf.name}
          </span>
          {/* m08 mockup 对齐：每张卡显示短 ID（末 6 位），方便和服务卡片
              "来自 {name} #xxxxxx" 互查。完整 ID hover title 看。 */}
          <span
            title={`workflow_id=${wf.id}`}
            style={{
              fontSize: 10,
              fontFamily: 'var(--mono, monospace)',
              color: 'var(--muted)',
            }}
          >
            #{shortWfId(String(wf.id))}
          </span>
        </div>
        <div
          style={{
            fontSize: 11,
            color: 'var(--muted)',
            display: 'flex',
            gap: 8,
            alignItems: 'center',
          }}
        >
          {isTemplate ? (
            <Badge color="purple">模板</Badge>
          ) : isPublished ? (
            <Badge color="green">已发布</Badge>
          ) : (
            <Badge>未发布</Badge>
          )}
          <span>
            {nodeCount} 节点
            {wf.status === 'draft' && ' · 编辑中'}
          </span>
        </div>
      </button>

      {!isTemplate && (
        <div
          style={{
            marginTop: 6,
            paddingTop: 10,
            borderTop: '1px dashed var(--border)',
            display: 'flex',
            gap: 6,
            alignItems: 'center',
          }}
        >
          {service ? (
            <>
              <span
                style={{
                  flex: 1,
                  fontSize: 11,
                  color: 'var(--muted)',
                  overflow: 'hidden',
                  textOverflow: 'ellipsis',
                  whiteSpace: 'nowrap',
                }}
              >
                服务：
                <button
                  type="button"
                  onClick={() => onDetail(service.id)}
                  style={{
                    background: 'transparent',
                    border: 'none',
                    color: 'var(--accent-2, #22c55e)',
                    fontFamily: 'var(--mono, monospace)',
                    cursor: 'pointer',
                    padding: 0,
                  }}
                >
                  {service.name}
                </button>
                <span style={{ color: 'var(--muted)', fontSize: 10, marginLeft: 4 }}>
                  v{service.version}
                </span>
              </span>
              <button
                type="button"
                onClick={onOpen}
                title="再次发布"
                style={{
                  padding: '3px 8px',
                  fontSize: 11,
                  color: 'var(--muted)',
                  background: 'var(--bg)',
                  border: '1px solid var(--border)',
                  borderRadius: 3,
                  cursor: 'pointer',
                }}
              >
                ↻ v{service.version + 1}
              </button>
            </>
          ) : (
            <>
              <span
                style={{
                  flex: 1,
                  fontSize: 11,
                  color: 'var(--muted)',
                }}
              >
                {isPublished ? '已发布 · 未关联服务' : '未关联服务'}
              </span>
              <button
                type="button"
                onClick={(e) => {
                  // 不冒泡到外层卡片 onOpen，否则跳画布根本不弹发布对话框
                  e.stopPropagation()
                  onPublish()
                }}
                style={{
                  padding: '3px 8px',
                  fontSize: 11,
                  color: 'var(--accent)',
                  background: 'var(--accent-subtle, rgba(99,102,241,0.1))',
                  border: '1px solid var(--accent-subtle, rgba(99,102,241,0.2))',
                  borderRadius: 3,
                  cursor: 'pointer',
                }}
              >
                发布为服务
              </button>
            </>
          )}
        </div>
      )}
    </div>
  )
}

